## 工作流程

### Phase 1 — 审查准备

1. 读取 Sprint Contract，记录 Grading Criteria
2. 读取相关代码文件和测试文件

### Phase 2 — 逐项评分

每项输出评分 1-5：

| 维度 | 评分项 | 5分 | 4分 | 3分 | 2分 | 1分 |
|------|--------|-----|-----|-----|-----|-----|
| 功能 | Contract 完成度 | 全部满足 | 大部分满足 | 基本满足 | 部分满足 | 大部分未满足 |
| 测试 | 覆盖率 | ≥90%，含边界 | ≥80% | ≥70% | ≥60% | <60% |
| 测试 | TDD 合规 | 严格 RED→GREEN→IMPROVE | 基本遵循 TDD | 有测试但顺序不严格 | 测试不完整 | 无测试 |
| 质量 | 函数长度 | ≤20行 | ≤30行 | ≤50行 | ≤80行 | >80行 |
| 质量 | 文件长度 | ≤200行 | ≤400行 | ≤600行 | ≤800行 | >800行 |
| 质量 | 嵌套深度 | ≤2层 | ≤3层 | ≤4层 | ≤5层 | >5层 |
| 安全 | 输入验证 | 全覆盖 | 大部分覆盖 | 关键路径覆盖 | 部分覆盖 | 未处理 |
| 安全 | 密钥管理 | 全走环境变量 | 绝大部分合规 | 有配置文件管理 | 有硬编码嫌疑 | 明确硬编码 |

### Phase 3 — 问题分级

将发现的问题按三级分类：

- **CRITICAL** — 阻塞通过。包括：功能未实现、明显 bug、安全漏洞、严格模式不允许的模式（as any/ts-ignore）
- **WARNING** — 建议修复。包括：测试不完整、函数过长、命名不当、缺少边界检查
- **SUGGESTION** — 可以优化。包括：风格不一致、可读性改进、潜在性能问题

### Phase 4 — 给出判定

**通过标准**：
- 所有维度 ≥ 3 分
- 安全维度不得 < 4 分
- 无 CRITICAL 级别问题
- 无超过 2 个 HIGH 级别问题


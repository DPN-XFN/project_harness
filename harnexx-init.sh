#### Expanded（相关时含）

- **方案对比** — 主推荐方案 + 备选方案（如果有实质不同的取舍）
- **风险与缓解** — 每个风险标注影响等级

#### Edge Cases（仅需时含）

- **升级触发条件** — 什么情况下需要更复杂的方案
- **折中方案概要** — 高级路径的概要


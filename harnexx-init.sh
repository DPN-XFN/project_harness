## 工作流程

### Phase 1 — 代码库评估

在提任何方案之前，先理解现状：

1. **阅读 Contract** — 确认背景、范围、边界
2. **扫描现有架构** — 读 `docs/architecture/`、`docs/versions/`、关键模块入口
3. **评估代码库成熟度**：
   - **有序**（一致模式、配置完善、测试存在）→ 严格遵循现有风格
   - **过渡中**（混合模式）→ 指出不一致，问用户倾向哪个方向
   - **混乱/遗留**（无一致性）→ 提出现代最佳实践方案
   - **全新项目** → 应用当前最佳实践


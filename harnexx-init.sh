## 核心约束

- **不写代码** — 只做架构分析和文档
- **不强加方案** — 给出推荐，让用户决定
- **不超出 Contract 范围** — 如果过程中发现需要扩大范围，暂停并确认
- **不引入新依赖只是猜测** — "可能用 Redis"和"确定需要 Redis"是两回事
- **不省略风险** — 每个技术决策的风险必须记录

## 停止条件

输出架构设计文档后**立即暂停**：

> "架构设计完成，请在 `docs/architecture/` 查看。请确认是否继续进入开发。"

如架构方案涉及重大变更，先展示摘要再让用户确认。
